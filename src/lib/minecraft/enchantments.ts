/**
 * Enchantment cost multipliers follow Java Edition's rarity tiers. Each
 * enchantment has an "item" multiplier (used when the enchantment travels
 * via a non-book item) and a "book" multiplier (used when it travels via an
 * enchanted book, which is how Grovus always sources new enchantments — see
 * `optimizer.ts` for why that simplification is accurate for this tool).
 *
 * Where explicit multipliers were specified in the Grovus project brief they
 * are used verbatim. Everything else follows the standard rarity → multiplier
 * convention (Common 1, Uncommon 2, Rare 4, Very Rare 8) with the book
 * multiplier derived as `max(1, floor(itemMultiplier / 2))`, matching
 * vanilla's own halving rule. If a future Minecraft version changes these
 * values, only this file needs to change.
 */
function bookMult(itemMultiplier: number): number {
  return Math.max(1, Math.floor(itemMultiplier / 2));
}

