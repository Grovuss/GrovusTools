const BY_ID = new Map(ENCHANTMENTS.map((e) => [e.id, e]));

export function getEnchantment(id: string): Enchantment {
  const e = BY_ID.get(id);
  if (!e) throw new Error(`Unknown enchantment id: ${id}`);
  return e;
}

export function enchantmentsForItem(item: ItemCategory): Enchantment[] {
  return ENCHANTMENTS.filter((e) => e.compatibleItems.includes(item));
}

